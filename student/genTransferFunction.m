function [TF] = genTransferFunction(x,u,p)
% GENTRANSFERFUNCTION Generate the rocket's linear transfer functions.
%
%   This function uses the linearized state-space model to generate the
%   transfer functions relating the rocket control inputs to its
%   translational and rotational velocities.
%
% Inputs:
%   x - Rocket state at the equilibrium point, [6x1].
%   u - Control input at the equilibrium point, [2x1].
%   p - Structure containing the rocket parameters.
%
% Outputs:
%   TF - 3x2 transfer-function matrix:
%
%        [ Vx/tau    Vx/delta
%          Vy/tau    Vy/delta
%          Omega/tau Omega/delta ]
%
%       where:
%       Vx    = horizontal velocity
%       Vy    = vertical velocity
%       Omega = angular velocity
%       tau   = throttle
%       delta = gimbal angle
%
% Notes:
%   - Use the linearized model generated by genLinearModel.
%   - The input and output ordering must match the definitions above.
%   - The transfer functions should be generated from the linear
%     state-space model.


[A,B] = genLinearModel(p);

C = [eye(3) zeros(3)];   % outputs: vx, vy, omega
D = zeros(3,2);

TF = minreal(tf(ss(A,B,C,D)), 1e-8);
end